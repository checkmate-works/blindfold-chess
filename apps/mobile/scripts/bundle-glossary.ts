/**
 * Copies the web's chess glossary seed (`apps/web/src/lib/db/data/chess-terms.ts`)
 * into `src/features/glossary/generated/terms.ts`: each term's English and
 * Japanese name, definitions, aliases and category. The web reads the
 * glossary from its database, seeded from that file; the app bundles the
 * seed so the glossary works offline. Board positions attached to terms are
 * left out.
 *
 * Run from apps/mobile: `pnpm bundle-glossary`. Generated, not edited by hand.
 */
import { mkdir, writeFile } from "fs/promises";
import { join, resolve } from "path";
import { pathToFileURL } from "url";

type WebTerm = {
  term: string;
  termJa?: string;
  definition: string;
  definitionEn?: string;
  aliases?: string[];
  relatedTerms?: string[];
  category?: string;
};

/** The web's `slugifyTerm` (apps/web/src/lib/glossary/slug.ts), so slugs match its URLs. */
function slugify(term: string): string {
  return term
    .toLowerCase()
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "");
}

async function main() {
  const source = resolve("../web/src/lib/db/data/chess-terms.ts");
  const { chessTerms } = (await import(pathToFileURL(source).href)) as {
    chessTerms: readonly WebTerm[];
  };
  const terms = chessTerms.map((t) => ({
    slug: slugify(t.term),
    term: t.term,
    termJa: t.termJa ?? t.term,
    definitionJa: t.definition,
    definitionEn: t.definitionEn ?? t.definition,
    aliases: t.aliases ?? [],
    relatedTerms: (t.relatedTerms ?? []).map(slugify),
    category: t.category ?? "general",
  }));
  const outDir = resolve("src/features/glossary/generated");
  await mkdir(outDir, { recursive: true });
  await writeFile(
    join(outDir, "terms.ts"),
    "// Generated by scripts/bundle-glossary.ts from the web app. Do not edit.\n/* eslint-disable */\n" +
      `import type { GlossaryTerm } from "../types";\n\nexport const GLOSSARY_TERMS: readonly GlossaryTerm[] = ${JSON.stringify(terms, null, 2)};\n`,
  );
  console.log(`${terms.length} terms`);
}

void main();
