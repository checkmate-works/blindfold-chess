/**
 * Copies the web's learn articles (`apps/web/.../learn/_content`) and the
 * figures they show (`apps/web/public/images/learn/*.svg`) into
 * `src/features/learn/generated/`, so the app can show them offline.
 *
 * Run from apps/mobile after the web articles change:
 * `pnpm bundle-learn-content`. The output is generated, not edited by hand.
 * Articles have no Brazilian-Portuguese text yet; the app falls back to
 * English for them.
 */
import { readFile, readdir, writeFile, mkdir } from "fs/promises";
import { join, resolve } from "path";
import { pathToFileURL } from "url";

const WEB = resolve("../web");
const CONTENT_DIR = join(WEB, "src/app/[locale]/(public)/learn/_content");
const IMAGE_DIR = join(WEB, "public/images/learn");
const OUT_DIR = resolve("src/features/learn/generated");
const LOCALES = ["en", "ja", "es"] as const;

type Article = {
  slug: string;
  category: string;
  difficulty: string;
  publishedAt: string;
  title: Record<string, string>;
  excerpt: Record<string, string>;
  body: Record<string, string>;
};

async function load<T>(path: string): Promise<T> {
  return (await import(pathToFileURL(path).href)) as T;
}

async function main() {
  const slugs = (await readdir(CONTENT_DIR)).sort();
  const articles: Article[] = [];
  for (const slug of slugs) {
    const dir = join(CONTENT_DIR, slug);
    const { commonMetadata } = await load<{
      commonMetadata: {
        category: string;
        difficulty: string;
        publishedAt: string;
      };
    }>(join(dir, "metadata.common.ts"));
    const article: Article = {
      slug,
      category: commonMetadata.category,
      difficulty: commonMetadata.difficulty,
      publishedAt: commonMetadata.publishedAt,
      title: {},
      excerpt: {},
      body: {},
    };
    for (const locale of LOCALES) {
      const { metadata } = await load<{
        metadata: { title: string; excerpt: string };
      }>(join(dir, `metadata.${locale}.ts`));
      const body = await load<{ default: string }>(join(dir, `${locale}.ts`));
      article.title[locale] = metadata.title;
      article.excerpt[locale] = metadata.excerpt;
      article.body[locale] = body.default;
    }
    articles.push(article);
  }

  const images: Record<string, string> = {};
  for (const file of (await readdir(IMAGE_DIR)).sort()) {
    if (!file.endsWith(".svg")) continue;
    images[`/images/learn/${file}`] = (
      await readFile(join(IMAGE_DIR, file), "utf8")
    ).trim();
  }

  await mkdir(OUT_DIR, { recursive: true });
  const header =
    "// Generated by scripts/bundle-learn-content.ts from the web app. Do not edit.\n/* eslint-disable */\n";
  await writeFile(
    join(OUT_DIR, "articles.ts"),
    `${header}import type { LearnArticle } from "../types";\n\nexport const LEARN_ARTICLES: readonly LearnArticle[] = ${JSON.stringify(articles, null, 2)};\n`,
  );
  await writeFile(
    join(OUT_DIR, "images.ts"),
    `${header}\n/** SVG markup of the articles' figures, keyed by the path the markdown uses. */\nexport const LEARN_IMAGES: Readonly<Record<string, string>> = ${JSON.stringify(images, null, 2)};\n`,
  );
  console.log(
    `${articles.length} articles, ${Object.keys(images).length} images`,
  );
}

void main();
