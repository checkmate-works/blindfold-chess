const SIGNUP_METHOD_ICONS: Record<Exclude<SignupMethod, 'unknown'>, ReactNode> = {
  google: <GoogleIcon />,
  email: <EnvelopeIcon />,
};

/**
 * The users-list "Signup method" cell as an icon. The name moves to `title`
 * (hover) and `aria-label` (screen readers), so the column stays narrow and
 * scans at a glance. `unknown` has no icon to stand for it and keeps its text.
 */
export function SignupMethodIcon({ method, label }: { method: SignupMethod; label: string }) {
  if (method === 'unknown') {
    return <span className="text-xs text-muted-foreground">{label}</span>;
  }
  return (
    <span role="img" aria-label={label} title={label} className="inline-flex">
      {SIGNUP_METHOD_ICONS[method]}
    </span>
  );
}
