/**
 * Leaderboard rank-update card (ランクイン) — the "〇〇 entered the
 * leaderboard" item a challenge save writes to the home feed when it lands
 * the player in the all-time top ranks.
 *
 * @description
 * One `feed_items` row per qualifying save, `entity_type =
 * 'challenge_rank_update'`, with `entity_id` naming the `challenge_results`
 * row and `actor_id` the player. The card takes likes (owner notified) but no
 * replies.
 *
 * Kept free of `server-only` and of DB imports so the client card and the
 * server side can share these constants.
 *
 * @design Likes target the feed row, not the result
 * The like is keyed on `feed_items.id`, the same choice the arrival
 * announcement makes (`MEMBER_JOINED_LIKE_TARGET`). The row is what the
 * viewer saw and liked, and it is what the 30-day reaper deletes: keying on
 * it lets the reaper delete the likes by the very ids it reaps, in one
 * transaction. The result row outlives the card, so keying on it would leave
 * likes nobody can see and nothing would clean up.
 *
 * @design Likes earn no coins
 * `LIKE_GRANT_TARGET_TYPES` (`@/lib/points/constants`) deliberately leaves
 * this type out. The card is generated by a score, not made by the player,
 * and paying per like would turn a leaderboard entry into a coin source —
 * exactly what the challenge anti-cheat checks exist to keep scores from
 * being worth faking for. Likes still count and still notify.
 *
 * @design A hidden card cannot be liked
 * The like action only accepts a row the feed would show (`liveFeedRow`):
 * once moderation removes the result, or the actor is gone, the card is
 * hidden and a like on it is refused. Likes given before the removal stay
 * until the reaper deletes the row; nobody can see them in the meantime.
 */

/** `feed_items.entity_type` of a leaderboard rank update. */
export const RANK_UPDATE_ENTITY_TYPE = 'challenge_rank_update';

/**
 * `likes.target_type` for a like on a rank-update card. The like targets the
 * `feed_items.id` — see the module TSDoc for why not the result id.
 */
export const RANK_UPDATE_LIKE_TARGET = 'challenge_rank_update';
