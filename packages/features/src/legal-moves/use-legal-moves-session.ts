"use client";

import { useCallback } from "react";

import { useBufferedQuestions } from "../practice-session/use-buffered-questions";
import { useTimedPracticeCompletion } from "../practice-session/use-practice-completion";
import {
  type TimedQuizSessionConfig,
  type TimedSessionFacade,
  toTimedSessionFacade,
} from "../practice-session/quiz-session";
import { useTimedSession } from "../practice-session/use-timed-session";
import { legalMovesChallengeDefinition } from "./challenge";
import { generateBalancedMoveQuestions } from "./logic";
import type { LegalMovesResult, MoveQuestion, PieceType } from "./types";

export type UseLegalMovesSessionConfig = TimedQuizSessionConfig<
  LegalMovesResult,
  MoveQuestion
> & {
  selectedPieces: PieceType[];
};

export type UseLegalMovesSessionReturn = TimedSessionFacade & {
  currentQuestion: MoveQuestion | null;
  /**
   * `userAnswer` is the player's claim that the move is legal (`true`) or
   * illegal (`false`); it is scored against {@link isLegalMove}.
   */
  handleAnswer: (userAnswer: boolean) => void;
};

/**
 * Timed legal-moves drill: say whether the shown move is legal.
 *
 * With `remote` the server supplies the questions (generated by
 * `legalMovesChallengeDefinition` with the same generator as the local
 * buffer) and the player's claim is sent to it as the raw answer. Answers are
 * graded with the definition's `grade` in both modes, so the on-screen
 * verdict matches the server's.
 */
export function useLegalMovesSession({
  timeLimit,
  selectedPieces,
  onComplete,
  onAnswerEffect,
  mistakeAllowance,
  remote,
  disablePause,
}: UseLegalMovesSessionConfig): UseLegalMovesSessionReturn {
  const generateQuestion = useBufferedQuestions(
    (count) => generateBalancedMoveQuestions(count, selectedPieces),
    { initialCount: 100 },
  );

  const session = useTimedSession<MoveQuestion>({
    timeLimit,
    generateQuestion,
    onAnswerEffect,
    mistakeAllowance,
    remote,
    disablePause,
  });

  useTimedPracticeCompletion(session, timeLimit, onComplete);

  const { handleAnswer: sessionHandleAnswer, currentQuestion } = session;

  const handleAnswer = useCallback(
    (userAnswer: boolean) => {
      if (!currentQuestion) return;
      const correct = legalMovesChallengeDefinition.grade(
        currentQuestion,
        userAnswer,
      );
      sessionHandleAnswer(correct, userAnswer);
    },
    [currentQuestion, sessionHandleAnswer],
  );

  return {
    ...toTimedSessionFacade(session),
    currentQuestion,
    handleAnswer,
  };
}
