"use client";

import { useCallback, useRef } from "react";

import type { BoardOrientation, Square } from "@blindfold-chess/types";

import {
  FEEDBACK_SPEED_MS,
  type FeedbackSpeed,
} from "../common/feedback-speed";
import { usePracticeCompletion } from "../practice-session/use-practice-completion";
import {
  type TimedQuizSessionConfig,
  type TimedSessionFacade,
  toTimedSessionFacade,
} from "../practice-session/quiz-session";
import { useTimedSession } from "../practice-session/use-timed-session";
import {
  coordinateQuizChallengeDefinition,
  rememberRecentSquare,
} from "./challenge";
import { generateSingleQuestion, calculateScore } from "./logic";
import type { CoordinateQuestion, QuizResult } from "./types";

export type UseCoordinateQuizSessionConfig = TimedQuizSessionConfig<
  QuizResult,
  CoordinateQuestion
> & {
  orientation: BoardOrientation;
  feedbackSpeed: FeedbackSpeed;
};

export type UseCoordinateQuizSessionReturn = TimedSessionFacade & {
  currentQuestion: CoordinateQuestion | null;
  handleAnswer: (square: Square) => void;
};

/**
 * Timed coordinate quiz: tap the named square. Each question's target avoids
 * the previous 8 targets, and an `orientation` of `"random"` is resolved
 * afresh per question, so the board may flip between questions. The
 * feedback flash length comes from `FEEDBACK_SPEED_MS[feedbackSpeed]`.
 *
 * With `remote` the server supplies the questions (generated by
 * `coordinateQuizChallengeDefinition` with the same no-repeat rule) and the
 * tapped square is sent to it as the raw answer. Answers are graded with the
 * definition's `grade` in both modes, so the on-screen verdict matches the
 * server's.
 */
export function useCoordinateQuizSession({
  timeLimit,
  orientation,
  feedbackSpeed,
  onComplete,
  onAnswerEffect,
  mistakeAllowance,
  remote,
  disablePause,
}: UseCoordinateQuizSessionConfig): UseCoordinateQuizSessionReturn {
  const recentSquaresRef = useRef<Square[]>([]);

  const generateQuestion = useCallback((): CoordinateQuestion => {
    const question = generateSingleQuestion(
      orientation,
      recentSquaresRef.current,
    );
    recentSquaresRef.current = rememberRecentSquare(
      recentSquaresRef.current,
      question.targetSquare,
    );
    return question;
  }, [orientation]);

  const session = useTimedSession<CoordinateQuestion>({
    timeLimit,
    generateQuestion,
    feedbackDuration: FEEDBACK_SPEED_MS[feedbackSpeed],
    onAnswerEffect,
    mistakeAllowance,
    remote,
    disablePause,
  });

  const { correctCount, incorrectCount, timeElapsed, isFinished } = session;

  usePracticeCompletion(
    isFinished,
    (): QuizResult => {
      const total = correctCount + incorrectCount;
      const timeTaken = Math.min(timeElapsed, timeLimit);
      const { points, accuracy, averageTime } = calculateScore(
        correctCount,
        total,
        timeTaken,
        timeLimit,
      );
      return {
        correctAnswers: correctCount,
        totalQuestions: total,
        accuracy,
        timeTaken,
        averageTime,
        points,
      };
    },
    onComplete,
  );

  const { handleAnswer: sessionHandleAnswer, currentQuestion } = session;

  const handleAnswer = useCallback(
    (square: Square) => {
      if (!currentQuestion) return;
      const correct = coordinateQuizChallengeDefinition.grade(
        currentQuestion,
        square,
      );
      sessionHandleAnswer(correct, square);
    },
    [currentQuestion, sessionHandleAnswer],
  );

  return {
    ...toTimedSessionFacade(session),
    currentQuestion,
    handleAnswer,
  };
}
